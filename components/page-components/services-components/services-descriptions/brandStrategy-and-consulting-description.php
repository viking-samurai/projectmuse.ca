		for what will work to build and sell your brand.
	</p>
	<p class="main-offers-paragraph">
		It is essential to understand that branding is a process that involves, but is not limited to:		
		<ul>
			<li><strong><u>Graphics and Colours</u>: </strong>What is the feel of your business and its 
				pressence and how do you express this feeling through the use of pictures and colours?</li>
			<li><strong><u>Form and flow</u>: </strong>What is the shape of your business and your 
				product and how do you project this shape, but within your store, and within the larger 
				community.</li>
			<li><strong><u>Style and Typography</u>: </strong>Words sell, and the type of words you choose 
				to build your brand have a strong impact on the communities that your brand will reach.</li>
			<li><strong><u>Taste and Cultural</u>: </strong>Your business occupies a unique spot within the 
				communities it serves.  How do people perceive your brand within these communites, and whether 
				you belong.</li>
			<li><strong><u>Delivery preferences</u>: </strong>Your business is fast.  You always deliver the 
				best, garanteed.  How people percieve the quality of your promise, and whether you deliver 
				has a huge impact on your brand.</li>
		</ul>
