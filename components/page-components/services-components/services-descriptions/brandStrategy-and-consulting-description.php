		</header>
	<p class="main-offers-paragraph">
		Effective brand management is an exploration of the company's intentions, against the perceptions 
		of the people buying the product.  At Project Muse, I start by developing your brand strategy, based 
		on your SEO profile, as well as your company's three year plan.  It's from the Discord chat, as well 
