		The three-step process is designed to engage with you about your ideas, test their viability, and develop 
		a sound product.  Following this process allows us to work together in smaller sections at a time, 
		while always maintaining the larger picture of what we're working towards.  The three step process 
		looks like this:
		<ul>
			<li><strong><u>Step 1</u>: </strong>Designing your website.</li>
			<li><strong><u>Step 2</u>: </strong>Developing your website.</li>
			<li><strong><u>Step 3</u>: </strong>Databasing your website.</li>
		</ul>
	</p>
