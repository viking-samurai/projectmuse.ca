		<header>
			<h3>Step 1: <span style="color: #12a8f2;">Designing your Website</span></h3>
		</header>
		<p class="main-offers-paragraph">
			A proper design for your new website is an essential component for its overall success.  And a website 
			design that isn't backed by a functioning business plan is a disaster waiting to happen.  That's how come 
			every new build by Project Muse starts with a rich discovery process, where I evaluate your needs and goals, 
			both for your website right now, but also for your business or organization in three to five years.  This 
			strategy is the quintessential reason people choose full-stack web development, as it helps us build your 
			new project in phases and components, and prevents costly issues from developing years after you launch 
			by planning for different opportunities early into the build.
		</p>
		<p class="main-offers-paragraph">
			At the end of this stage, you get a web application blueprint, as well as a minimum viable product (MVP).
			This blueprint will be shared between us, and serve as an organic document, informing the website or web
			application's current and future development.  The mvp will be the final product of this stage and will 
			be a coded version of the web applications's initial design, with stock images and filler text, presented 
			through Github Pages.  This wireframe and blueprint are intended for you to start your networking, and should 
			be seen as an opportunity to try different looks with different groups, gather early feedback, and debug any 
			issues with the starting template.
		</p>
